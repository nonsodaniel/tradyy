export const SECTORS = [...new Set(COMPANIES.map((c) => c.sector))].sort();

export function searchCompanies(query: string, sector?: string, status?: CompanyStatus): Company[] {
  const q = query.toLowerCase();
  return COMPANIES.filter((c) => {
    const matchesQuery =
      !q ||
      c.name.toLowerCase().includes(q) ||
      c.ticker?.toLowerCase().includes(q) ||
      c.ceo.toLowerCase().includes(q) ||
      c.sector.toLowerCase().includes(q) ||
      c.industry.toLowerCase().includes(q);
    const matchesSector = !sector || c.sector === sector;
    const matchesStatus = !status || c.status === status;
    return matchesQuery && matchesSector && matchesStatus;
  });
}
